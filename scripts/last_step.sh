#!/usr/bin/env bash
# The cut's gate: this exits 0 from the cut's root only when every check below is green. Red means not done. Run it
# bare: never pipe it into tail or head, which hides the exit status and the failing step's output.
#
#   scripts/last_step.sh
#
# Setup, which stops the run at the first problem: Node 24 or later; npm ci when node_modules is missing or older
# than the lock; .venv from scripts/requirements-dev.txt when missing or stale (AC_PYTHON picks the Python that
# creates it, default python3, 3.11 or later); the Rust toolchain that rust-toolchain.toml pins (rustup installs it),
# with cargo-llvm-cov and cargo-deny (or cargo-audit). Then every check runs, in this order, and the summary lists
# each: Biome lint, Biome format check, tsc -b, the unit tests with the coverage floors, the e2e suite (after a
# release build of ac-relay, whose path it gets as AC_RELAY_CMD), the vectors check and scripts/verify_vectors.py,
# the Python join example (examples/python-join/check.sh, against that relay and the CLI), the Rust checks (cargo
# fmt, clippy with warnings as errors, cargo test, the coverage floors of coverage-floors.toml with cargo llvm-cov,
# the crate-age cooldown, cargo deny or cargo audit), check-imports, check-pragmas, check-size (the ceilings of
# size-ceilings.toml), the Python tests, the adversarial cases regenerated byte for byte, and the npm packages
# bundled into @usebag/bag checked for advisories (scripts/check-bundled-advisories.mjs, which asks the registry).
# There is no coverage-ratchet check here: the ratchet compares thresholds with another branch, and this repository
# has one commit, so there is nothing to compare with; size-ceilings.toml is checked as it stands. A skipped, todo,
# cancelled or ignored test is not run, and it turns its step red. Temporary files go under AC_TEST_TMP (default
# TMPDIR, else /tmp); nothing is written into the repository but gitignored output (node_modules, .venv, coverage/,
# target/). Check 25 comes last: the relay's Rust crate notices are current and every licence is allowed
# (scripts/rust-notices.mjs --check, crates/ac-relay/THIRD-PARTY-RUST.md).
set -euo pipefail

cd "$(dirname "$0")/.."
need_node=24
python=.venv/bin/python
tmp_root="${AC_TEST_TMP:-${TMPDIR:-/tmp}}"
tmp_root="${tmp_root%/}"

setup_failed() {
  echo "last_step: $*" >&2
  echo "last_step: RED at setup" >&2
  exit 1
}

# --- setup -------------------------------------------------------------------------------------------------------

have="$(node -p 'process.versions.node' 2>/dev/null || true)"
if [[ -z "$have" || "${have%%.*}" -lt $need_node ]]; then
  echo "last_step: this repository needs Node $need_node or later (.nvmrc); found ${have:-no node} at $(command -v node || echo 'no path')" >&2
  echo "  with nvm:  . ~/.nvm/nvm.sh && nvm install $need_node && nvm use $need_node" >&2
  echo "  or put a Node $need_node+ bin first in PATH" >&2
  exit 1
fi

if [[ ! -f node_modules/.package-lock.json || package-lock.json -nt node_modules/.package-lock.json ]]; then
  echo "== setup: npm ci (node_modules is missing or older than package-lock.json)"
  npm ci --no-audit --no-fund || setup_failed "npm ci failed"
fi

want="$(node -e 'const c = require("node:crypto"), fs = require("node:fs")
process.stdout.write(c.createHash("sha256").update(fs.readFileSync("scripts/requirements-dev.txt")).digest("hex"))')"
if [[ ! -x "$python" || "$(cat .venv/.requirements.sha256 2>/dev/null || true)" != "$want" ]]; then
  boot="${AC_PYTHON:-python3}"
  "$boot" -I -c 'import sys; sys.exit(sys.version_info < (3, 11))' 2>/dev/null ||
    setup_failed "$boot is missing or older than Python 3.11; set AC_PYTHON"
  echo "== setup: .venv from scripts/requirements-dev.txt (missing or stale)"
  "$boot" -m venv --clear .venv || setup_failed "python -m venv failed"
  "$python" -I -m pip install --quiet --disable-pip-version-check --no-deps --only-binary=:all: \
    -r scripts/requirements-dev.txt || setup_failed "pip install failed"
  "$python" -I -m pip check --disable-pip-version-check || setup_failed "pip check failed"
  printf '%s\n' "$want" >.venv/.requirements.sha256
fi
mkdir -p "$tmp_root" || setup_failed "cannot create $tmp_root"

# Rust: rustup's cargo, the pinned toolchain and the two cargo tools.
if ! command -v cargo >/dev/null 2>&1 && [[ -x "$HOME/.cargo/bin/cargo" ]]; then
  PATH="$HOME/.cargo/bin:$PATH"
fi
if ! command -v cargo >/dev/null 2>&1 || ! command -v rustup >/dev/null 2>&1; then
  setup_failed "cargo and rustup are not in PATH; install rustup (https://rustup.rs)"
fi
pinned="$(sed -n 's/^channel = "\(.*\)"$/\1/p' rust-toolchain.toml)"
[[ -n "$pinned" ]] || setup_failed "rust-toolchain.toml names no channel"
if ! rustup toolchain list | grep -q "^$pinned-"; then
  setup_failed "the pinned Rust toolchain $pinned is not installed; run: rustup toolchain install (in this worktree)"
fi
rust_version="$(rustc --version)"
[[ "$rust_version" == "rustc $pinned "* ]] || setup_failed "rustc is $rust_version, not the pinned $pinned"
cargo llvm-cov --version >/dev/null 2>&1 ||
  setup_failed "cargo-llvm-cov is missing: cargo install cargo-llvm-cov --locked --version 0.8.7"
if cargo deny --version >/dev/null 2>&1; then
  advisories=deny
elif cargo audit --version >/dev/null 2>&1; then
  advisories=audit
else
  setup_failed "neither cargo-deny nor cargo-audit is installed: cargo install cargo-deny --locked --version 0.20.2"
fi
cargo_tmp="$tmp_root/bag-cargo-$(basename "$PWD")"
mkdir -p "$cargo_tmp" || setup_failed "cannot create $cargo_tmp"

# --- helpers -----------------------------------------------------------------------------------------------------

names=()
results=()
seconds=()
facts=()

step() { # step <name> <command> [args...]: runs one check, records ok or RED and its time
  local name="$1" t0=$SECONDS
  shift
  echo
  echo "== $name"
  if "$@"; then results+=("ok"); else results+=("RED"); fi
  names+=("$name")
  seconds+=("$((SECONDS - t0))")
}

# The packages whose package.json has the given script.
packages_with() {
  # shellcheck disable=SC2016 # the ${...} is a JavaScript template literal, for node, not the shell
  node -e 'const fs = require("node:fs")
    for (const d of fs.readdirSync("packages").sort()) {
      const f = `packages/${d}/package.json`
      if (fs.existsSync(f) && JSON.parse(fs.readFileSync(f, "utf8")).scripts?.[process.argv[1]]) console.log(d)
    }' "$1"
}

# test_report <label> <since, ms> <vitest json report>...: one line of counts; exit 1 on a missing or stale report,
# a failed test, or a skipped or todo one (not run).
test_report() {
  local line
  if line="$(node - "$@" <<'EOF'
const fs = require('node:fs')
const [label, since, ...files] = process.argv.slice(2)
const n = { passed: 0, failed: 0, skipped: 0, todo: 0, total: 0 }
const problems = []
for (const f of files) {
  let r
  try {
    r = JSON.parse(fs.readFileSync(f, 'utf8'))
  } catch {
    problems.push(`${f}: no report`)
    continue
  }
  if (!(r.startTime >= Number(since))) problems.push(`${f}: a stale report, from before this run`)
  n.passed += r.numPassedTests
  n.failed += r.numFailedTests
  n.skipped += r.numPendingTests
  n.todo += r.numTodoTests
  n.total += r.numTotalTests
}
if (n.skipped + n.todo > 0) problems.push(`${n.skipped + n.todo} skipped or todo: not run`)
if (n.failed > 0) problems.push(`${n.failed} failed`)
const where = files.length === 1 ? '1 report' : `${files.length} reports`
console.log(`${label}: ${n.passed} passed, ${n.failed} failed, ${n.skipped} skipped, ${n.todo} todo, of ${n.total} (${where})` +
  (problems.length ? `; RED: ${problems.join('; ')}` : ''))
process.exit(problems.length ? 1 : 0)
EOF
  )"; then
    echo "$line"
    facts+=("$line")
  else
    echo "$line" >&2
    facts+=("$line")
    return 1
  fi
}

# coverage_line <since, ms> <package>...: each package's four coverage numbers from its fresh coverage summary.
coverage_line() {
  local line
  if line="$(node - "$@" <<'EOF'
const fs = require('node:fs')
const [since, ...pkgs] = process.argv.slice(2)
const parts = []
let bad = false
for (const p of pkgs) {
  const f = `packages/${p}/coverage/coverage-summary.json`
  if (!fs.existsSync(f) || fs.statSync(f).mtimeMs < Number(since)) {
    parts.push(`${p} no fresh summary`)
    bad = true
    continue
  }
  const t = JSON.parse(fs.readFileSync(f, 'utf8')).total
  parts.push(`${p} ${['statements', 'branches', 'functions', 'lines'].map((m) => t[m].pct).join('/')}`)
}
console.log(`coverage (statements/branches/functions/lines): ${parts.join(', ')}`)
process.exit(bad ? 1 : 0)
EOF
  )"; then
    echo "$line"
    facts+=("$line")
  else
    echo "$line" >&2
    facts+=("$line")
    return 1
  fi
}

unit_tests() {
  local since status=0 pkgs=() reports=() p
  since="$(node -p 'Date.now()')"
  while IFS= read -r p; do [[ -n "$p" ]] && pkgs+=("$p"); done < <(packages_with test)
  [[ ${#pkgs[@]} -gt 0 ]] || { echo "no package has a test script" >&2; return 1; }
  for p in "${pkgs[@]}"; do reports+=("packages/$p/coverage/test-results.json"); done
  npm test || status=1
  test_report "unit tests" "$since" "${reports[@]}" || status=1
  coverage_line "$since" "${pkgs[@]}" || status=1
  return $status
}

e2e_tests() {
  local since status=0
  since="$(node -p 'Date.now()')"
  # The e2e harness starts the Rust relay from AC_RELAY_CMD.
  cargo build --release --locked -p ac-relay || return 1
  AC_RELAY_CMD="$PWD/target/release/ac-relay" npm run test:e2e || status=1
  test_report "e2e" "$since" packages/e2e/coverage/test-results.json || status=1
  return $status
}

vectors() {
  local status=0
  npm run vectors:check || status=1
  "$python" -I -B scripts/verify_vectors.py || status=1
  return $status
}

# python_join: the Python participant of examples/python-join, which shares no code with packages/ or crates/,
# against the release relay the e2e step built and the CLI; its last line of output is its summary.
python_join() {
  local out status=0 last
  out="$(AC_RELAY_CMD="$PWD/target/release/ac-relay" AC_TEST_TMP="$tmp_root" examples/python-join/check.sh)" ||
    status=1
  echo "$out"
  last="${out##*$'\n'}"
  [[ "$last" == python-join:* ]] || last="python-join: no summary line; RED"
  facts+=("$last")
  return $status
}

python_tests() {
  local bt xml line
  bt="$tmp_root/bag-pytest-$(basename "$PWD")"
  xml="$bt.junit.xml"
  "$python" -I -B -m pytest tests/python -q -p no:cacheprovider --basetemp="$bt" --junitxml="$xml" || return 1
  line="$("$python" -I -c '
import sys
import xml.etree.ElementTree as ET
root = ET.parse(sys.argv[1]).getroot()
s = root if root.tag == "testsuite" else root.find("testsuite")
total, skipped, failed = int(s.get("tests")), int(s.get("skipped")), int(s.get("failures")) + int(s.get("errors"))
print(f"python tests: {total - skipped - failed} passed, {failed} failed, {skipped} skipped, of {total}")
sys.exit(1 if skipped or failed else 0)
' "$xml")" || {
    echo "$line (a skipped test is not run)" >&2
    facts+=("$line; RED")
    return 1
  }
  facts+=("$line")
}

# rust_tests: cargo test over the workspace (unit, integration and doc tests), with one line of counts; an ignored
# test is not run and turns the step red.
rust_tests() {
  local out="$cargo_tmp/cargo-test.txt" line
  cargo test --workspace --locked 2>&1 | tee "$out" || return 1
  if line="$(awk '/^test result:/ {
      for (i = 1; i < NF; i++) {
        if ($(i + 1) ~ /^passed/) p += $i
        if ($(i + 1) ~ /^failed/) f += $i
        if ($(i + 1) ~ /^ignored/) g += $i
      }
      n++
    }
    END {
      printf "rust tests: %d passed, %d failed, %d ignored, in %d test binaries", p, f, g, n
      exit (f + g > 0 || n == 0)
    }' "$out")"; then
    echo "$line"
    facts+=("$line")
  else
    echo "$line; RED (an ignored test is not run)" >&2
    facts+=("$line; RED")
    return 1
  fi
}

# floor <key>: a value of coverage-floors.toml (one `key = value` per line; strings in single quotes).
floor() {
  awk -v key="$1" -v q="'" '$0 ~ "^[[:space:]]*" key "[[:space:]]*=" {
      line = $0
      sub(/^[^=]*=[[:space:]]*/, "", line)
      sub(/[[:space:]]+(#.*)?$/, "", line)
      if (length(line) >= 2 && substr(line, 1, 1) == q && substr(line, length(line), 1) == q) line = substr(line, 2, length(line) - 2)
      print line
      exit
    }' coverage-floors.toml
}

# rust_coverage: cargo llvm-cov with the floors of coverage-floors.toml (lines, functions and regions; branch
# coverage is nightly-only and not gated), and one line with the three numbers of the workspace and of each crate.
rust_coverage() {
  local json="$cargo_tmp/llvm-cov-$$.json" line status=0
  # A name of its own for this run: a failed run writes no report, and the last run's report never stands in for it.
  cargo llvm-cov --workspace --locked --json --summary-only --output-path "$json" \
    --ignore-filename-regex "$(floor ignore_filename_regex)" \
    --fail-under-lines "$(floor lines)" --fail-under-functions "$(floor functions)" \
    --fail-under-regions "$(floor regions)" || status=1
  if line="$(node - "$json" <<'NODE'
const fs = require('node:fs')
let report
try {
  report = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'))
} catch {
  console.log('rust coverage: no report')
  process.exit(1)
}
const metrics = ['lines', 'functions', 'regions']
const pct = (t) => metrics.map((m) => (t[m].count ? (100 * t[m].covered) / t[m].count : 100).toFixed(2)).join('/')
const crates = {}
for (const f of report.data[0].files) {
  const name = (f.filename.match(/crates\/([^/]+)\//) || [])[1]
  if (!name) continue
  crates[name] ??= Object.fromEntries(metrics.map((m) => [m, { count: 0, covered: 0 }]))
  for (const m of metrics) {
    crates[name][m].count += f.summary[m].count
    crates[name][m].covered += f.summary[m].covered
  }
}
const parts = [`workspace ${pct(report.data[0].totals)}`, ...Object.keys(crates).sort().map((k) => `${k} ${pct(crates[k])}`)]
console.log(`rust coverage (lines/functions/regions): ${parts.join(', ')}`)
NODE
  )"; then
    echo "$line"
  else
    echo "$line" >&2
    status=1
  fi
  facts+=("$line")
  return $status
}

# crate_age: the 7-day cooldown on Cargo.lock, after the script's own offline self-test.
crate_age() {
  local line
  "$python" -I -B scripts/check-crate-age.py --self-test >/dev/null || {
    echo "check-crate-age: the self-test failed" >&2
    return 1
  }
  if line="$(AC_TEST_TMP="$tmp_root" "$python" -I -B scripts/check-crate-age.py)"; then
    echo "$line"
    facts+=("$line")
  else
    facts+=("check-crate-age: RED")
    return 1
  fi
}

# rust_advisories: cargo deny (advisories, licenses, bans, sources; deny.toml), else cargo audit alone.
rust_advisories() {
  if [[ "$advisories" == deny ]]; then
    cargo deny --locked check
  else
    echo "cargo-deny is not installed: cargo audit alone"
    facts+=("rust advisories: cargo audit only (cargo-deny is not installed)")
    cargo audit
  fi
}

# rust_notices: check 25. The notices of the Rust crates the relay binary is built from,
# crates/ac-relay/THIRD-PARTY-RUST.md, are what scripts/rust-notices.mjs writes from Cargo.lock, and every crate's
# licence is one deny.toml allows (its allow list and its per-crate exceptions). It reads cargo metadata --offline, so
# it runs after the Rust steps have filled the cargo cache; a cargo failure is red, never a pass.
rust_notices() {
  local out line status=0
  out="$tmp_root/bag-rust-notices-$(basename "$PWD").txt"
  node scripts/rust-notices.mjs --check 2>&1 | tee "$out"
  [[ ${PIPESTATUS[0]} -eq 0 ]] || status=1
  line="$(awk '/^rust-notices: (pass|.* is stale|[0-9]+ crate)/ { l = $0 } END { print l }' "$out")"
  [[ -n "$line" ]] || { line="rust-notices: no summary line"; status=1; }
  [[ $status -eq 0 ]] || line="$line; RED"
  facts+=("$line")
  return $status
}

# adversarial: regenerates spec/adversarial/*.json (the differential cases, seed 20261025) under AC_TEST_TMP and fails
# unless every file is byte-identical; its last "adversarial:check: OK" or "FAIL" line goes to the summary.
adversarial() {
  local out line status=0
  out="$tmp_root/bag-adversarial-$(basename "$PWD").txt"
  AC_TEST_TMP="$tmp_root" npm run adversarial:check 2>&1 | tee "$out" || status=1
  line="$(awk '/^adversarial:check: (OK|FAIL)/ { l = $0 } END { print l }' "$out")"
  [[ -n "$line" ]] || { line="adversarial:check: no summary line"; status=1; }
  [[ $status -eq 0 ]] || line="$line; RED"
  facts+=("$line")
  return $status
}

# bundled_advisories: check 24. The npm packages bundled into @usebag/bag (the build's own list, each at
# the lock's version) have no advisory at any severity: scripts/check-bundled-advisories.mjs builds the bundle under
# AC_TEST_TMP and runs npm audit on a synthetic lockfile of exactly those packages (the registry's bulk advisory
# endpoint, no token). Its one summary line goes to the summary; a build or registry failure is red, never a pass.
bundled_advisories() {
  local out line status=0
  out="$tmp_root/bag-bundled-advisories-$(basename "$PWD").txt"
  AC_TEST_TMP="$tmp_root" node scripts/check-bundled-advisories.mjs 2>&1 | tee "$out"
  [[ ${PIPESTATUS[0]} -eq 0 ]] || status=1
  line="$(awk '/^check-bundled-advisories: (pass|[0-9]+ advisory)/ { l = $0 } END { print l }' "$out")"
  [[ -n "$line" ]] || { line="check-bundled-advisories: no summary line"; status=1; }
  [[ $status -eq 0 ]] || line="$line; RED"
  facts+=("$line")
  return $status
}

