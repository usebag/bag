# --- summary -----------------------------------------------------------------------------------------------------

echo
echo "last_step: summary (Node $have, npm $(npm --version), $("$python" -I -c 'import platform; print("Python", platform.python_version())'), $rust_version)"
red=()
for i in "${!names[@]}"; do
  printf '  %-4s %-62s %4ss\n' "${results[$i]}" "${names[$i]}" "${seconds[$i]}"
  [[ "${results[$i]}" == ok ]] || red+=("${names[$i]}")
done
if [[ ${#facts[@]} -gt 0 ]]; then
  for f in "${facts[@]}"; do echo "  $f"; done
fi
if [[ ${#red[@]} -gt 0 ]]; then
  echo "last_step: RED: ${#red[@]} of ${#names[@]} checks failed; not done"
  exit 1
fi
echo "last_step: GREEN (${#names[@]} of ${#names[@]} checks)"
